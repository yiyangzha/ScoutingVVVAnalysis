@dataclass
class Scenario:
    scope: str  # combined / class / sample
    name: str
    signal_samples: list


def build_scenarios(reg, scopes=()):
    out = [Scenario("combined", "combined", sorted(set(reg.signal_samples)))]
    out += [Scenario("class", c, sorted(set(reg.class_members[c]))) for c in reg.class_order if c in reg.signal_classes]
    out += [Scenario("sample", s, [s]) for s in reg.signal_samples]
    return [s for s in out if not scopes or s.scope in scopes]


@dataclass
class MassProcess:
    name: str
    member_samples: list = field(default_factory=list)
    hist: list = field(default_factory=list)  # [region] -> (yields, sumw2) lists; empty: the fitted QCD
    smoothed: bool = False
    norm_error: list = field(default_factory=list)


def _copy_regions(regions):
    return [(list(y), list(w)) for y, w in regions]


def _add_regions(dst, src):
    if not dst:
        return _copy_regions(src)
    for (dy, dw), (sy, sw) in zip(dst, src):
        for j in range(len(dy)):
            dy[j] += sy[j]
            dw[j] += sw[j]
    return dst


def _required(hists, key, kind, channel):
    if key not in hists:
        raise CardError(f"Missing massfit {kind} '{key}' in channel '{channel}'")
    return hists[key]


def massfit_card_bins(mf):
    """Mass bins of a card: those with fail-region QCD MC, or with qcd_from_mc every bin."""
    if mf.qcd_from_mc:
        return [True] * mf.n_bins
    return [mf.qcd_true[0][0][j] > 0.0 for j in range(mf.n_bins)]


def smooth_pass_templates(proc, loose, card_bin):
    """combine.C smoothPassTemplates: box total over the card bins x the loosened box shape."""
    proc.smoothed = True
    proc.norm_error = [0.0] * len(loose)
    for i, (ly, lw) in enumerate(loose):
        by, bw = proc.hist[i + 1]
        total = total_sumw2 = loose_total = 0.0
        for j in range(len(card_bin)):
            if not card_bin[j]:
                continue
            total += by[j]
            total_sumw2 += bw[j]
            loose_total += ly[j]
        if not total > 0.0 or not loose_total > 0.0:
            continue
        for j in range(len(card_bin)):
            l = ly[j]  # noqa: E741
            value = total * l / loose_total if card_bin[j] and l > 0.0 else 0.0
            by[j] = value
            bw[j] = value * value * max(lw[j], 0.0) / (l * l) if value > 0.0 else 0.0
        proc.norm_error[i] = math.sqrt(max(total_sumw2, 0.0)) / total


def build_mass_processes(ch, reg, sc, use_fit):
    """combine.C buildMassProcesses: signal first, then the backgrounds in class order."""
    mf = ch.massfit
    sig = MassProcess("signal")
    if sc.scope == "sample":
        s = sc.signal_samples[0]
        sig.hist = _copy_regions(_required(mf.sample, s, "sample", ch.name))
        sig.member_samples = [s]
    else:
        for cls in reg.class_order:
            is_signal = cls in reg.signal_classes if sc.scope == "combined" else cls == sc.name
            if not is_signal:
                continue
            sig.hist = _add_regions(sig.hist, _required(mf.group, slugify(cls), "group", ch.name))
            sig.member_samples += reg.class_members[cls]
    out = [sig]
    qcd_added = False
    for cls in reg.class_order:
        if sc.scope == "combined" and cls in reg.signal_classes:
            continue
        if sc.scope == "class" and cls == sc.name:
            continue
        if use_fit and reg.is_qcd_class(cls):
            if not qcd_added:
                out.append(MassProcess("bkg_qcd"))
                qcd_added = True
            continue
        if sc.scope == "sample":
            for s in reg.class_members[cls]:
                if s in sc.signal_samples or s not in mf.sample:
                    continue
                out.append(MassProcess("bkg_" + slugify(s), [s], _copy_regions(mf.sample[s])))
        else:
            bkg = MassProcess("bkg_" + slugify(cls), list(reg.class_members[cls]),
                              _copy_regions(_required(mf.group, slugify(cls), "group", ch.name)))
            if slugify(cls) in mf.smooth:
                smooth_pass_templates(bkg, mf.smooth[slugify(cls)], massfit_card_bins(mf))
            out.append(bkg)
    return out


def is_qcd_mass_process(reg, proc):
    """The fitted QCD, or MC whose samples are all in QCD classes."""
    if not proc.hist:
        return True
    for s in proc.member_samples:
        if s not in reg.sample_to_class or not reg.is_qcd_class(reg.sample_to_class[s]):
            return False
    return bool(proc.member_samples)


def bernstein_basis(n, v, t):
    c = 1.0
    for i in range(1, v + 1):
        c = c * (n - v + i) / i
    return c * math.pow(t, v) * math.pow(1.0 - t, n - v)


def slope_name(channel, sr_id):
    return f"n_{channel}_sr{sr_id}_slope"


