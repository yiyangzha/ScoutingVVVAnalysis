def run_tag(sc, use_fit, tag_prefix=""):
    """combine.C buildAndRun work-directory tag."""
    prefix = slugify(tag_prefix) + "_" if tag_prefix else ""
    return f"{prefix}{'abcd' if use_fit else 'mc'}_{slugify(sc.scope)}_{slugify(sc.name)}"


def write_scenario(cfg, reg, channels, sc, use_fit, tag_prefix="", log=log_message):
    """The cards of one scenario and QCD mode (the card-writing part of combine.C buildAndRun). Returns the
    manifest entry; the combineCards.py / Combine part is vvv.stats.combine_run."""
    tag = run_tag(sc, use_fit, tag_prefix)
    work = Path(cfg.work_dir) / tag
    entry = {"tag": tag, "scope": sc.scope, "name": sc.name, "mode": "abcd" if use_fit else "mc",
             "channel": tag_prefix[len("channel_"):] if tag_prefix else None,
             "channels": [ch.name for ch in channels], "work": str(work), "cards": [], "card_channels": [],
             "masked_bins": [], "slope_params": [], "skipped_zero_signal_channels": [], "status": "ok", "error": None}
    try:
        work.mkdir(parents=True, exist_ok=True)
        for ch in channels:
            out = write_massfit_card(cfg, reg, ch, sc, use_fit, work, log=log)
            if out is not None:
                entry["cards"].append(out.card_path)
                entry["card_channels"].append(ch.name)
                # combineCards.py names the bins of its k-th card ch<k>_<bin>.
                k = len(entry["cards"])
                entry["masked_bins"] += [f"ch{k}_{b}" for b in out.masked_bins]
                if use_fit:
                    entry["slope_params"] += [slope_name(ch.name, ch.sr_ids[i]) for i in range(ch.n_sr)
                                              if ch.massfit.sr_slope[i]]
                continue
            if sc.scope == "sample" or len(channels) == 1:
                log(f"WARNING: Dropping zero-yield signal channel from scenario: channel={ch.name} "
                    f"scenario={sc.scope}/{sc.name} qcd_mode={entry['mode']}")
                entry["skipped_zero_signal_channels"].append(ch.name)
                continue
            raise CardError(f"Signal process is identically zero for scenario '{sc.scope}/{sc.name}' in channel "
                            f"'{ch.name}'")
        if not entry["cards"]:
            if sc.scope == "sample" or len(channels) == 1:
                log("WARNING: Signal scenario is identically zero in all usable channels; storing significance=0 "
                    f"and infinite expected limits: scenario={sc.scope}/{sc.name} qcd_mode={entry['mode']} "
                    f"skipped_channels={','.join(entry['skipped_zero_signal_channels'])}")
                entry["status"] = "zero_signal"
            else:
                raise CardError(f"No usable channels remain for scenario '{sc.scope}/{sc.name}'")
    except CardError as e:
        log(f"ERROR: scenario failed, storing nan: scope={sc.scope} name={sc.name} qcd_mode={entry['mode']}"
            + (f" {tag_prefix}" if tag_prefix else "") + f": {e}")
        entry["status"], entry["error"] = "failed", str(e)
    return entry


def write_all(cfg, log=log_message):
    """Every scenario of combine.C runMain: per scenario the MC-QCD and fitted-QCD cards of all channels, then
    per channel every scenario alone. Writes <output_dir>/datacards.json (the manifest run_combine reads)."""
    Path(cfg.work_dir).mkdir(parents=True, exist_ok=True)
    reg = load_registry(cfg, log=log)
    log(f"Loaded registry: classes={len(reg.class_order)}, signal_classes={len(reg.signal_classes)}, "
        f"signal_samples={len(reg.signal_samples)}, qcd_classes={len(reg.qcd_classes)}")
    channels = load_channels(cfg, reg, log=log)
    scenarios = build_scenarios(reg, cfg.scenario_scopes)
    log(f"Scenarios: {len(scenarios)}; data_mode={cfg.data_mode}")
    runs = []
    for sc in scenarios:
        for use_fit in (False, True):
            log(f"=== Scenario: scope={sc.scope} name={sc.name} ({'ABCD' if use_fit else 'MC true'} QCD) ===")
            runs.append(write_scenario(cfg, reg, channels, sc, use_fit, log=log))
    for ch in channels:
        for sc in scenarios:
            for use_fit in (False, True):
                log(f"=== Channel scenario: channel={ch.name} scope={sc.scope} name={sc.name} "
                    f"({'ABCD' if use_fit else 'MC true'} QCD) ===")
                runs.append(write_scenario(cfg, reg, [ch], sc, use_fit, "channel_" + ch.name, log=log))
    manifest = {
        "config": cfg.path, "output_dir": cfg.output_dir, "work_dir": cfg.work_dir, "data_mode": cfg.data_mode,
        "combine_cmd": cfg.combine_cmd, "combine_cards_cmd": cfg.combine_cards_cmd, "keep_work": cfg.keep_work,
        "channels": [{"name": c.name, "root_file": c.root_file, "bdt_root": c.bdt_root, "mc_lumi": ch.massfit.mc_lumi,
                      "data_lumi": ch.massfit.data_lumi} for c, ch in zip(cfg.channels, channels)],
        "enabled_nuisances": sorted(cfg.enabled_nuisances), "syst_inputs": cfg.inputs,
        "ignored_settings": {"eigen_rel_cutoff": cfg.eigen_rel_cutoff,
                             "rescale_shape_modes_to_positive": cfg.rescale_shape_modes_to_positive},
        "scenarios": [{"scope": s.scope, "name": s.name} for s in scenarios],
        "runs": runs,
    }
    path = Path(cfg.output_dir) / "datacards.json"
    path.write_text(json.dumps(manifest, indent=1))
    n_failed = sum(r["status"] == "failed" for r in runs)
    log(f"Wrote {path}: {len(runs)} runs, {n_failed} failed")
    return manifest
