@dataclass
class SampleInfo:
    name: str
    is_mc: bool
    is_signal: bool
    has_theory_weights: bool


@dataclass
class Registry:
    class_order: list
    class_members: dict
    sample_to_class: dict
    signal_classes: set
    signal_samples: list
    qcd_classes: list
    samples: dict

    def is_qcd_class(self, cls):
        return cls in self.qcd_classes


def load_registry_from_bdt_root(bdt_root, label):
    """combine.C loadRegistryFromBdtRoot: <bdt_root>/config.json (or fold0/) class_groups + sample_config."""
    root = Path(bdt_root)
    cfg_dir = root / "fold0" if not (root / "config.json").exists() and (root / "fold0" / "config.json").exists() \
        else root
    bdt = load_json(str((cfg_dir / "config.json").resolve()))
    # sample_config is relative to the nearest selections/BDT ancestor of bdt_root, else to its parent.
    base = root.parent
    for d in [root.resolve(), *root.resolve().parents]:
        if d.name == "BDT" and d.parent.name == "selections":
            base = d
            break
    sample_json = load_json(resolve_path(str(base), bdt["sample_config"]))
    samples = {}
    for node in sample_json["sample"]:
        samples[node["name"]] = SampleInfo(node["name"], bool(node["is_MC"]), bool(node["is_signal"]),
                                           bool(node.get("has_theory_weights", False)))
    if "class_groups" not in bdt:
        raise CardError(f"{label} bdt_root/config.json missing 'class_groups'")
    reg = Registry([], {}, {}, set(), [], [], samples)
    for cls, members in bdt["class_groups"].items():
        reg.class_order.append(cls)
        all_signal, anything = True, False
        for s in members:
            reg.sample_to_class[s] = cls
            if s not in samples:
                raise CardError(f"{label} class_groups references unknown sample: {s}")
            all_signal = all_signal and samples[s].is_signal
            anything = True
        reg.class_members[cls] = list(members)
        if anything and all_signal:
            reg.signal_classes.add(cls)
        if "qcd" in slugify(cls):
            reg.qcd_classes.append(cls)
    if not reg.qcd_classes:
        raise CardError(f"{label} class_groups must contain at least one QCD class")
    for cls in reg.class_order:
        reg.signal_samples += [s for s in reg.class_members[cls] if samples[s].is_signal]
    return reg


def load_registry(cfg, log=log_message):
    """combine.C loadRegistry: the channels' registries must agree; background classes get the union."""
    per_channel = [load_registry_from_bdt_root(ch.bdt_root, f"channel '{ch.name}'") for ch in cfg.channels]
    reg = per_channel[0]
    reg.class_members = {k: list(v) for k, v in reg.class_members.items()}
    ref_label = f"channel '{cfg.channels[0].name}'"
    for ch, cand in zip(cfg.channels[1:], per_channel[1:]):
        detail = (f"channel '{ch.name}' BDT registry differs from {ref_label}; combine.C requires all channel "
                  "bdt_root configs to share the same class order and signal/QCD definitions")
        if cand.class_order != reg.class_order:
            raise CardError(detail + " (class order mismatch)")
        if cand.signal_classes != reg.signal_classes:
            raise CardError(detail + " (signal class mismatch)")
        for cls in reg.signal_classes:
            if cand.class_members[cls] != reg.class_members[cls]:
                raise CardError(detail + f" (members of signal class '{cls}' differ)")
        if cand.signal_samples != reg.signal_samples:
            raise CardError(detail + " (signal sample mismatch)")
        if cand.qcd_classes != reg.qcd_classes:
            raise CardError(detail + " (QCD class mismatch)")
        for s, cls in cand.sample_to_class.items():
            if s in reg.sample_to_class and reg.sample_to_class[s] != cls:
                raise CardError(detail + f" (sample '{s}' is in class '{cls}' here and in class "
                                f"'{reg.sample_to_class[s]}' there)")
        for cls in reg.class_order:
            for s in cand.class_members[cls]:
                if s in reg.class_members[cls]:
                    continue
                reg.class_members[cls].append(s)
                reg.sample_to_class[s] = cls
                reg.samples.setdefault(s, cand.samples[s])
    for ch, cand in zip(cfg.channels, per_channel):
        absent = sorted(s for s in reg.sample_to_class if s not in cand.sample_to_class)
        if absent:
            log(f"Channel '{ch.name}': its class_groups lack {len(absent)} background sample(s) of the other "
                f"channels (zero yield there): {', '.join(absent)}")
    return reg


