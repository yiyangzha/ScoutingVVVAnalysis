def _th1(name, value, error):
    """TH1D(name, name, 1, 0, 1) with SetBinContent(1, value) and SetBinError(1, error), as combine.C writes it."""
    from uproot.writing.identify import to_TAxis, to_TH1x

    return to_TH1x(fName=name, fTitle=name, data=np.array([0.0, value, 0.0]), fEntries=1.0, fTsumw=0.0,
                   fTsumw2=0.0, fTsumwx=0.0, fTsumwx2=0.0, fSumw2=np.array([0.0, error * error, 0.0]),
                   fXaxis=to_TAxis(fName="xaxis", fTitle="", fNbins=1, fXmin=0.0, fXmax=1.0))


def write_shape_file(path, histograms):
    """histograms: {bin name: [(process name, value, error), ...]} -> one TDirectory per bin."""
    import uproot

    with uproot.recreate(path) as f:
        for bin_name, hists in histograms.items():
            for name, value, error in hists:
                f[f"{bin_name}/{name}"] = _th1(name, value, error)


def massfit_card_text(cfg, reg, ch, procs, bins, shape_path, fit_qcd, log=log_message):
    """The card of writeMassfitCard (everything after the bins and their entries are fixed)."""
    mf = ch.massfit
    card_bin = massfit_card_bins(mf)
    digits = max(2, len(str(max(mf.n_bins - 1, 0))))
    cells = [(b, e) for b in bins for e in b.entries]
    lines = [CARD_HEADER, f"imax {len(bins)}", "jmax *", "kmax *", "----------",
             f"shapes * * {shape_path} $CHANNEL/$PROCESS", "----------",
             "bin" + "".join(" " + b.name for b in bins),
             "observation" + " -1" * len(bins), "----------",
             "bin" + "".join(" " + b.name for b, _ in cells),
             "process" + "".join(" " + procs[e.proc].name for _, e in cells),
             "process" + "".join(f" {e.proc}" for _, e in cells),
             "rate" + " -1" * len(cells), "----------"]

    def row(name, kind, value):
        vals = [value(b, e) for b, e in cells]
        if any(v != "-" for v in vals):
            lines.append(f"{name} {kind}" + "".join(" " + v for v in vals))

    def pass_mc(b, e):
        return b.region > 0 and bool(procs[e.proc].member_samples)

    for name, unc in (("lumi", cfg.lumi_unc), ("trigger", cfg.trigger_unc)):
        if cfg.enabled(name):
            kappa = fixed6(1.0 + unc)
            row(name, "lnN", lambda b, e, k=kappa: k if pass_mc(b, e) else "-")
    if cfg.enabled("xsec"):
        # Background processes only: the signal (process 0) is scaled by r, which absorbs its cross section.
        for p, proc in enumerate(procs[1:], start=1):
            if not proc.member_samples:
                continue

            def xsec_cell(b, e, p=p, proc=proc):
                if e.proc != p or not pass_mc(b, e):
                    return "-"
                # A smoothed template can be positive where the box is empty: its samples are weighted by
                # their box yields over the SR's card bins instead of the bin's.
                total = weighted = 0.0
                for s in proc.member_samples:
                    if s not in mf.sample:
                        continue
                    box = mf.sample[s][b.region][0]
                    y = box[b.j]
                    if proc.smoothed:
                        y = 0.0
                        for j in range(mf.n_bins):
                            if card_bin[j]:
                                y += box[j]
                    if not y > 0.0:
                        continue
                    total += y
                    weighted += y * sample_xsec_unc(cfg, s)
                if not total > 0.0 or not weighted > 0.0:
                    return "-"
                return fixed6(1.0 + weighted / total)

            row("xsec_" + proc.name, "lnN", xsec_cell)
    for spec in RATIO_SPECS:
        sums = cfg.syst_sums.get(spec.nuisance)
        if sums is None:
            continue
        binned = False
        for sample, trees in sums.items():
            ss = trees.get(ch.name)
            if ss is None or not ss.mass_edges:
                continue
            binned = True
            e = ss.mass_edges
            same = len(e) == len(mf.edges) and all(abs(e[i] - mf.edges[i]) <= 1e-6 * max(1.0, abs(mf.edges[i]))
                                                   for i in range(len(e)))
            if not same:
                raise CardError(f"{spec.config_key}: the mass bins of sample '{sample}' in channel '{ch.name}' differ "
                                "from the qcd_est massfit bins")
        count = FallbackCount()
        kappas = {}

        def ratio_cell(b, e, only_process, spec=spec, sums=sums, binned=binned, count=count, kappas=kappas):
            p = e.proc
            if not pass_mc(b, e) or (only_process >= 0 and p != only_process):
                return "-"
            sr_id = ch.sr_ids[b.region - 1]
            if binned:
                def cell_yield(s):
                    return mf.sample[s][b.region][0][b.j] if s in mf.sample else 0.0
                k = process_kappa(spec, sums, ch.name, procs[p].name, procs[p].member_samples, reg.samples,
                                  cell_yield, e.value, "mass_bin", sr_id, b.j, count)
            else:
                key = (p, b.region)
                if key not in kappas:
                    def cell_yield(s):
                        return ch.sample_sr_yields[s][b.region - 1] if s in ch.sample_sr_yields else 0.0
                    kappas[key] = process_kappa(spec, sums, ch.name, procs[p].name, procs[p].member_samples,
                                                reg.samples, cell_yield, e.value, "window", sr_id, -1, count)
                k = kappas[key]
            return f"{fixed6(k.down)}/{fixed6(k.up)}" if k.active else "-"

        if spec.nuisance == "theory_scale":
            for p, proc in enumerate(procs):
                row("theory_scale_" + proc.name, "lnN", lambda b, e, p=p, f=ratio_cell: f(b, e, p))
        else:
            row(spec.nuisance, "lnN", lambda b, e, f=ratio_cell: f(b, e, -1))
        log(f"    {spec.nuisance} ({ch.name}): "
            + ("mass-binned kappas of the merged processes" if binned
               else "per-SR kappas of the merged processes applied to every mass bin")
            + f", {count.cells} process cells, {count.fit_range} from the SR fit range, {count.inclusive} from the "
              "inclusive selection (too few effective events)")
    if cfg.enabled("autoMCStats"):
        for p, proc in enumerate(procs):
            for i, err in enumerate(proc.norm_error):
                if not err > 0.0:
                    continue
                kappa = fixed6(1.0 + err)
                row(f"mcnorm_{ch.name}_sr{ch.sr_ids[i]}_{proc.name}", "lnN",
                    lambda b, e, p=p, i=i, k=kappa: k if e.proc == p and b.region == i + 1 else "-")
        lines.append(f"* autoMCStats {cfg.mc_stat_threshold}")

    # QCD: free fail yields and, with the fit, the pass-bin formula.
    prefix = ch.name
    bern = []
    if fit_qcd:
        for i in range(ch.n_sr):
            # [0, 100]: on data (2026-10-26) the normalisation of SR4 reached the former bound 10.
            lines.append(f"n_{prefix}_sr{ch.sr_ids[i]} extArg 1 [0,100]")
            if mf.sr_slope[i]:
                lines.append(f"{slope_name(prefix, ch.sr_ids[i])} extArg 0 [-10,10]")
        for k in range(len(mf.eig)):
            lines.append(f"tf_{prefix}_e{k}" + (" extArg 0 [-20,20]" if mf.tfmc_free else " param 0 1"))
        for v in range(1, mf.residual_order + 1):
            bern.append(f"bern_{prefix}_{v}")
            lines.append(f"{bern[-1]} extArg 1 [{g10(mf.bern_low)},{g10(mf.bern_high)}]")
    for b in bins:
        qcd_f = f"qcdF_{prefix}_m{b.j:0{digits}d}"
        for e in b.entries:
            proc = procs[e.proc]
            if not is_qcd_mass_process(reg, proc):
                continue
            if b.region == 0:
                lines.append(f"{qcd_f} rateParam {b.name} {proc.name} 1 [0,10]")
                continue
            if proc.hist:
                continue  # QCD MC in the pass bins
            args = [qcd_f, f"n_{prefix}_sr{ch.sr_ids[b.region - 1]}"]
            expo = ""
            for k in range(len(mf.eig)):
                expo += ("+" if k else "") + f"({g10(mf.eig[k][b.j])})*@{len(args)}"
                args.append(f"tf_{prefix}_e{k}")
            t = 0.5 * (mf.x[b.j] + 1.0)
            poly = ""
            for v in range(1, mf.residual_order + 1):
                poly += f"+({g10(bernstein_basis(mf.residual_order, v, t))})*@{len(args)}"
                args.append(bern[v - 1])
            formula = "@0*@1"
            if expo:
                formula += f"*exp({expo})"
            if poly:
                formula += f"*({g10(bernstein_basis(mf.residual_order, 0, t))}{poly})"
            if mf.sr_slope[b.region - 1]:
                formula += f"*exp(({g10(mf.x[b.j])})*@{len(args)})"
                args.append(slope_name(prefix, ch.sr_ids[b.region - 1]))
            lines.append(f"qcd_{b.name} rateParam {b.name} {proc.name} ({formula}) {','.join(args)}")
    return "\n".join(lines) + "\n"


def massfit_bins(ch, procs, reg):
    """The bins of a massfit card and their process entries; also the signal yield of the pass bins."""
    mf = ch.massfit
    F = mf.qcd_true[0][0]
    card_bin = massfit_card_bins(mf)
    digits = max(2, len(str(max(mf.n_bins - 1, 0))))
    bins = []
    signal_pass = 0.0
    for region in range(1 if mf.qcd_from_mc else 0, ch.n_sr + 1):
        for j in range(mf.n_bins):
            if not card_bin[j]:
                continue
            name = ch.name + ("_fail_" if region == 0 else f"_sr{ch.sr_ids[region - 1]}_") + f"m{j:0{digits}d}"
            b = Bin(name, region, j, [])
            for p, proc in enumerate(procs):
                error = 0.0
                if not proc.hist:
                    value = F[j] if region == 0 else mf.n0[region - 1] * F[j] * mf.shape[j]
                else:
                    value = proc.hist[region][0][j]
                    if not (region == 0 and is_qcd_mass_process(reg, proc)):
                        error = math.sqrt(max(proc.hist[region][1][j], 0.0))
                if value > 0.0:
                    b.entries.append(Entry(p, value, error))
            if not any(e.proc > 0 for e in b.entries):
                continue
            for e in b.entries:
                if e.proc == 0 and region > 0:
                    signal_pass += e.value
            bins.append(b)
    return bins, signal_pass


def write_massfit_card(cfg, reg, ch, sc, use_fit, work, log=log_message):
    """combine.C writeMassfitCard: shapes_<channel>.root and card_<channel>.txt in work. None when the signal
    is identically zero in the pass bins."""
    if cfg.use_root_covariance:
        raise CardError(f"massfit channel '{ch.name}' needs use_root_covariance = false")
    mf = ch.massfit
    fit_qcd = use_fit and not mf.qcd_from_mc
    procs = build_mass_processes(ch, reg, sc, fit_qcd)
    bins, signal_pass = massfit_bins(ch, procs, reg)
    if not signal_pass > 0.0:
        return None
    shape_path = str(Path(work) / f"shapes_{ch.name}.root")
    masked = []
    hists = {}
    for b in bins:
        obs = 0.0
        hists[b.name] = []
        for e in b.entries:
            hists[b.name].append((procs[e.proc].name, e.value, e.error))
            obs += e.value
        if cfg.data_mode == "observed":
            obs = mf.data[b.region][b.j]
            if b.region > 0 and mf.blinded[b.region - 1][b.j]:
                masked.append(b.name)
        hists[b.name].append(("data_obs", obs, 0.0))
    write_shape_file(shape_path, hists)
    card_path = str(Path(work) / f"card_{ch.name}.txt")
    Path(card_path).write_text(massfit_card_text(cfg, reg, ch, procs, bins, shape_path, fit_qcd, log=log))
    log(f"  massfit card {card_path}: {len(bins)} bins, {len(procs)} processes, QCD "
        + ("fitted" if fit_qcd else "from MC (qcd_from_mc, pass bins only)" if mf.qcd_from_mc
           else "from MC in the pass bins"))
    return CardOutput(card_path, shape_path, masked)


