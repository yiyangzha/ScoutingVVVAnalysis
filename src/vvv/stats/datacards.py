def _get(f, path):
    """TFile::Get: the object, or None (uproot.KeyInFileError is a KeyError)."""
    try:
        return f[path]
    except KeyError:
        return None


def _one_bin(f, path):
    h = _get(f, path)
    if h is None or not hasattr(h, "values"):
        raise CardError(f"Missing one-bin histogram '{path}' in {f.file_path}")
    v = h.values()
    if v.ndim != 1 or len(v) != 1:
        raise CardError(f"Histogram '{path}' in {f.file_path} must have exactly one bin")
    return float(v[0])


def _contents(f, path, n_bins):
    h = _get(f, path)
    if h is None or not hasattr(h, "values"):
        raise CardError(f"Missing histogram '{path}' in {f.file_path}")
    v = h.values()
    if n_bins >= 0 and len(v) != n_bins:
        raise CardError(f"Histogram '{path}' in {f.file_path} has {len(v)} bins, expected {n_bins}")
    return [float(x) for x in v]


def _low_edges(h):
    """TAxis::GetBinLowEdge(1 .. n + 1)."""
    ax = h.member("fXaxis")
    n = ax.member("fNbins")
    xbins = ax.member("fXbins")
    if len(xbins):
        return [float(e) for e in xbins]
    lo, hi = ax.member("fXmin"), ax.member("fXmax")
    width = (hi - lo) / n
    return [lo + i * width for i in range(n + 1)]


def _subdirs(f, prefix):
    d = _get(f, prefix)
    if d is None:
        return []
    return sorted({k for k, c in d.classnames(recursive=False, cycle=False).items()
                   if c in ("TDirectory", "TDirectoryFile")})


def _signal_region_ids(f):
    t = _get(f, "metadata/signal_regions")
    if t is None:
        return []
    if "bin_index" not in t.keys():
        raise CardError(f"metadata/signal_regions in {f.file_path} is missing required branch 'bin_index'")
    ids = [int(v) for v in t["bin_index"].array(library="np")]
    if not ids:
        raise CardError(f"metadata/signal_regions in {f.file_path} must contain at least one row")
    seen = set()
    for i in ids:
        if i <= 0:
            raise CardError(f"metadata/signal_regions in {f.file_path} contains a non-positive bin_index")
        if i in seen:
            raise CardError(f"metadata/signal_regions in {f.file_path} contains duplicate bin_index={i}")
        seen.add(i)
    return ids


def _yield_cov(f, prefix, sr_ids):
    """combine.C readYieldCov: the one-bin SR bundle (yields, covariance) of a sample/group/qcd_predict."""
    h2 = _get(f, prefix + "/covariance_total")
    if h2 is None:
        raise CardError(f"Missing '{prefix}/covariance_total' in {f.file_path}")
    cov = h2.values()
    n = cov.shape[0]
    if n <= 0 or cov.shape[1] != n:
        raise CardError(f"Covariance size mismatch for {prefix}")
    ids = sr_ids or list(range(1, n + 1))
    if len(ids) != n:
        raise CardError(f"Signal-region metadata size mismatch for {prefix} in {f.file_path}: metadata has "
                        f"{len(ids)} entries but covariance has {n} bins")
    yields = []
    for i in ids:
        p = f"{prefix}/sr{i}"
        yields.append(_one_bin(f, p + "/yield"))
        for name in ("stat_error", "scale_error", "n_entries"):
            _one_bin(f, f"{p}/{name}")
    _one_bin(f, prefix + "/mean_event_weight")
    return yields, cov


def _validate_yield_cov(yc, label):
    yields, cov = yc
    if not yields:
        raise CardError(f"Empty yield/cov bundle for {label}")
    for i, y in enumerate(yields):
        if not math.isfinite(y):
            raise CardError(f"Non-finite yield in {label}")
        if y < 0.0:
            raise CardError(f"Negative nominal yield in {label}")
        if not np.all(np.isfinite(cov[i])):
            raise CardError(f"Non-finite covariance in {label}")
        if cov[i, i] < 0.0:
            raise CardError(f"Negative covariance diagonal in {label}")


def _mass_regions(f, rel, sr_ids, n_bins):
    paths = [f"massfit/fail/{rel}"] + [f"massfit/pass/{rel}/sr{i}" for i in sr_ids]
    return [(_contents(f, p + "/yield", n_bins), _contents(f, p + "/sumw2", n_bins)) for p in paths]


def load_channel(spec, registry, log=log_message):
    """combine.C loadChannel + validateChannelAgainstRegistry, for massfit channels."""
    import uproot

    log(f"Reading channel '{spec.name}' from {spec.root_file}")
    if not os.path.exists(spec.root_file):
        raise CardError(f"Channel ROOT file not found: {spec.root_file}")
    with uproot.open(spec.root_file) as f:
        meta_ids = _signal_region_ids(f)
        sample_names = _subdirs(f, "samples")
        if not sample_names:
            raise CardError(f"No samples/ entries in {spec.root_file}")
        samples = {s: _yield_cov(f, "samples/" + s, meta_ids) for s in sample_names}
        n_sr = len(samples[sample_names[0]][0])
        sr_ids = meta_ids or list(range(1, n_sr + 1))
        for s, yc in samples.items():
            if len(yc[0]) != n_sr:
                raise CardError(f"Inconsistent SR count for sample {s}")
        group_names = _subdirs(f, "groups")
        if not group_names:
            raise CardError(f"No groups/ entries in {spec.root_file}")
        groups = {}
        for g in group_names:
            if slugify(g) in groups:
                raise CardError(f"Duplicate groups/ entries after case-insensitive matching: '{g}' collides with "
                                f"another group in {spec.root_file}")
            groups[slugify(g)] = _yield_cov(f, "groups/" + g, sr_ids)
            if len(groups[slugify(g)][0]) != n_sr:
                raise CardError(f"Inconsistent SR count for group {slugify(g)}")
        qcd_predict = _yield_cov(f, "qcd_predict", sr_ids)
        _one_bin(f, "qcd_predict/abcd_scale")
        _one_bin(f, "qcd_predict/abcd_scale_error")
        csv_hash = ""
        if _get(f, "metadata/sr_csv_hash") is not None:
            csv_hash = format(int(_one_bin(f, "metadata/sr_csv_hash")), "013x")
        per_sr_abcd = _get(f, "qcd_predict/per_sr_abcd") is not None and _one_bin(f, "qcd_predict/per_sr_abcd") == 1.0
        massfit_on = (_get(f, "massfit/settings/enabled") is not None
                      and _one_bin(f, "massfit/settings/enabled") == 1.0)
        if massfit_on and per_sr_abcd:
            raise CardError(f"Channel '{spec.name}' holds both per-SR ABCD and massfit inputs")
        if not massfit_on:
            raise NotImplementedError(
                f"channel '{spec.name}' has no massfit inputs: the one-bin ABCD cards of combine.C "
                "(writeChannelDatacard, per-SR ABCD, use_root_covariance) are not ported")
        mf = MassfitData()
        mf.qcd_from_mc = (_get(f, "massfit/settings/qcd_from_mc") is not None
                          and _one_bin(f, "massfit/settings/qcd_from_mc") == 1.0)
        if mf.qcd_from_mc:
            h = _get(f, "massfit/fail/qcd_true/yield")
            if h is None:
                raise CardError(f"Missing histogram 'massfit/fail/qcd_true/yield' in {spec.root_file}")
            mf.n_bins = len(h.values())
            mf.edges = _low_edges(h)
            mf.sr_slope = [False] * n_sr
        else:
            mf.x = _contents(f, "massfit/tfmc/x", -1)
            mf.n_bins = len(mf.x)
            mf.shape = _contents(f, "massfit/tfmc/shape", mf.n_bins)
            mf.edges = _low_edges(f["massfit/tfmc/shape"])
            n_eig = int(_one_bin(f, "massfit/settings/n_eig"))
            mf.eig = [_contents(f, f"massfit/tfmc/eig{k}", mf.n_bins) for k in range(n_eig)]
            mf.n0 = _contents(f, "massfit/tfmc/n0", n_sr)
            if _get(f, "massfit/sr_slope") is not None:
                mf.sr_slope = [v != 0.0 for v in _contents(f, "massfit/sr_slope", n_sr)]
            else:
                mf.sr_slope = [False] * n_sr
            mf.residual_order = int(_one_bin(f, "massfit/settings/residual_order"))
            mf.tfmc_free = _one_bin(f, "massfit/settings/tfmc_free") == 1.0
            mf.bern_low = _one_bin(f, "massfit/settings/bern_low")
            mf.bern_high = _one_bin(f, "massfit/settings/bern_high")
        for s in sample_names:
            mf.sample[s] = _mass_regions(f, "samples/" + s, sr_ids, mf.n_bins)
        for g in group_names:
            mf.group[slugify(g)] = _mass_regions(f, "groups/" + g, sr_ids, mf.n_bins)
            sd = "massfit/smooth/" + g
            if _get(f, sd + "/factor") is None:
                continue
            mf.smooth[slugify(g)] = [(_contents(f, f"{sd}/sr{i}/yield", mf.n_bins),
                                      _contents(f, f"{sd}/sr{i}/sumw2", mf.n_bins)) for i in sr_ids]
            log(f"  channel '{spec.name}': smoothed pass templates of class '{g}' "
                f"(SR boxes loosened by {_one_bin(f, sd + '/factor'):g})")
        mf.qcd_true = _mass_regions(f, "qcd_true", sr_ids, mf.n_bins)
        if _get(f, "massfit/settings/mc_lumi") is not None:
            mf.mc_lumi = _one_bin(f, "massfit/settings/mc_lumi")
        if _get(f, "massfit/settings/data_lumi") is not None:
            mf.data_lumi = _one_bin(f, "massfit/settings/data_lumi")
        if _get(f, "massfit/settings/has_data") is not None and _one_bin(f, "massfit/settings/has_data") == 1.0:
            mf.has_data = True
            # A fit to data needs the MC at the data's luminosity.
            if mf.mc_lumi is None or mf.data_lumi is None:
                raise CardError(f"Channel '{spec.name}' has data but {spec.root_file} records no massfit/settings/"
                                "mc_lumi and data_lumi; re-run estimate_qcd.py")
            if abs(mf.mc_lumi - mf.data_lumi) > 1e-6 * abs(mf.data_lumi):
                raise CardError(f"Channel '{spec.name}': the MC is normalised to {mf.mc_lumi:g} fb^-1 but the data has "
                                f"{mf.data_lumi:g} fb^-1 in {spec.root_file}; re-run estimate_qcd.py with the MC at the "
                                "data luminosity")
            mf.data.append(_contents(f, "massfit/fail/data/yield", mf.n_bins))
            for i in sr_ids:
                mf.data.append(_contents(f, f"massfit/pass/data/sr{i}/yield", mf.n_bins))
                flags = [v != 0.0 for v in _contents(f, f"massfit/blinded/sr{i}", mf.n_bins)]
                for j in range(mf.n_bins):
                    if flags[j] and mf.data[-1][j] != 0.0:
                        raise CardError(f"Channel '{spec.name}': blinded data bin {j} of sr{i} is not empty")
                mf.blinded.append(flags)
    ch = ChannelData(spec.name, n_sr, sr_ids, {s: yc[0] for s, yc in samples.items()}, csv_hash, mf)
    # validateChannelAgainstRegistry
    for cls in registry.class_order:
        if slugify(cls) not in groups:
            raise CardError(f"Missing required group '{cls}' (matched as '{slugify(cls)}') in channel '{spec.name}'")
        _validate_yield_cov(groups[slugify(cls)], f"group '{cls}' (matched as '{slugify(cls)}') in channel "
                                                  f"'{spec.name}'")
    for s in registry.signal_samples:
        if s not in samples:
            raise CardError(f"Missing required signal sample '{s}' in channel '{spec.name}'")
        _validate_yield_cov(samples[s], f"signal sample '{s}' in channel '{spec.name}'")
    _validate_yield_cov(qcd_predict, f"qcd_predict in channel '{spec.name}'")
    mode = ("mass-binned pass bins, QCD from MC (qcd_from_mc, no QCD fit)" if mf.qcd_from_mc else
            f"pass/fail mass fit, {len(mf.eig)} TF_MC shape parameters "
            f"({'free' if mf.tfmc_free else 'constrained'}), residual order {mf.residual_order}")
    log(f"  channel '{spec.name}': {mode}, {mf.n_bins} mass bins, n_sr={n_sr}, sr_ids={sr_ids}, "
        f"samples={len(samples)}, groups={len(groups)}"
        + (f", MC at {mf.mc_lumi:g} fb^-1" if mf.mc_lumi is not None else "")
        + (f", data ({mf.data_lumi:g} fb^-1)" if mf.has_data else ""))
    return ch


def check_sr_provenance(sums, label, ch, log=log_message):
    """The syst sums must belong to the channel's signal regions (combine.C checkSrProvenance)."""
    unchecked = False
    for sample, trees in sums.items():
        ss = trees.get(ch.name)
        if ss is None or not ss.regions:
            continue
        if not ss.sr_csv_hash or not ch.sr_csv_hash:
            unchecked = True
            continue
        if ss.sr_csv_hash != ch.sr_csv_hash:
            raise CardError(f"{label}: the per-SR ratios of sample '{sample}' in channel '{ch.name}' were computed "
                            f"for other signal regions (SR CSV hash {ss.sr_csv_hash}) than the channel's qcd_est "
                            f"output ({ch.sr_csv_hash}); rerun the systematics with the current signal_region.csv")
    if unchecked:
        log(f"WARNING: {label}: per-SR ratios in channel '{ch.name}' cannot be matched to the channel's signal "
            "regions (no SR CSV hash in the JSON or in the qcd_est output; rerun both to enable the check)")


def load_channels(cfg, registry, log=log_message):
    channels = []
    for spec in cfg.channels:
        ch = load_channel(spec, registry, log=log)
        checked = set()
        for rs in RATIO_SPECS:
            if rs.nuisance not in cfg.syst_sums or rs.config_key in checked:
                continue
            checked.add(rs.config_key)
            check_sr_provenance(cfg.syst_sums[rs.nuisance], rs.config_key, ch, log=log)
        if cfg.data_mode == "observed" and not ch.massfit.has_data:
            raise CardError("data_mode observed needs massfit channels with data (qcd_est.py data_sample); "
                            f"channel '{ch.name}' has none")
        channels.append(ch)
    return channels


