@dataclass
class RegionSums:
    yield_: float = 0.0
    sumw2: float = 0.0
    varied: list = field(default_factory=list)
    varied_sumw2: list = field(default_factory=list)


@dataclass
class SampleSums:
    inclusive: RegionSums
    regions: dict
    mass_range: dict
    mass_bins: dict
    mass_edges: list
    sr_csv_hash: str
    min_region_events: int
    pdf_method: str = ""


def _read_numbers(node, key, n, where):
    if key not in node:
        raise CardError(f"{where} has no '{key}'")
    out = [float(v) for v in node[key]]
    if len(out) != n:
        raise CardError(f"{where}: '{key}' has {len(out)} entries, expected {n}")
    return out


def read_region_sums(node, spec, where):
    if "yield" not in node or "sumw2" not in node:
        raise CardError(f"{where} has no yields to add up over the samples of a process; re-run {spec.producer}")
    out = RegionSums(float(node["yield"]), float(node["sumw2"]))

    def varied(name, n):
        out.varied += _read_numbers(node, "yield_" + name, n, where)
        out.varied_sumw2 += _read_numbers(node, "sumw2_" + name, n, where)

    if spec.reduction == "updown":
        for key in (spec.up_key, spec.down_key):
            if "yield_" + key not in node or "sumw2_" + key not in node:
                raise CardError(f"{where} has no 'yield_{key}' and 'sumw2_{key}'; re-run {spec.producer}")
            out.varied.append(float(node["yield_" + key]))
            out.varied_sumw2.append(float(node["sumw2_" + key]))
    elif spec.reduction == "pdf":
        varied("pdf", 101)
        if "yield_alphas" in node:
            varied("alphas", 2)
        else:  # a PDF set without alpha_s members: the nominal yield
            out.varied += [out.yield_] * 2
            out.varied_sumw2 += [out.sumw2] * 2
    elif spec.reduction == "scale":
        varied("scale", 9)
    else:
        varied("ps", 4)
    return out


def load_syst_sums(payload, spec, path):
    """sample -> channel -> SampleSums of one nuisance (combine.C loadSystSums)."""
    out = {}
    for sample, trees in payload.items():
        for tree, v in trees.items():
            where = f"{path}: sample '{sample}' tree '{tree}'"
            if "regions" not in v:
                raise CardError(f"{where} has no per-signal-region ratios; configure bdt_root and "
                                f"signal_region_csv for {spec.producer}")
            if "min_region_events" not in v:
                raise CardError(f"{where} has no min_region_events; re-run {spec.producer}")
            ss = SampleSums(read_region_sums(v, spec, where), {}, {}, {}, [], v.get("sr_csv_hash", ""),
                            int(v["min_region_events"]))
            for reg, node in v["regions"].items():
                rid = int(reg)
                rw = f"{where} SR {reg}"
                ss.regions[rid] = read_region_sums(node, spec, rw)
                if "mass_range" in node:
                    ss.mass_range[rid] = read_region_sums(node["mass_range"], spec, rw + " fit range")
                if "mass_bins" in node:
                    ss.mass_bins[rid] = [read_region_sums(b, spec, rw + " mass bin") for b in node["mass_bins"]]
            if "mass_fit" in v:
                ss.mass_edges = [float(e) for e in v["mass_fit"]["edges"]]
            if spec.reduction == "pdf":
                ss.pdf_method = v["pdf_method"]
                if ss.pdf_method not in ("hessian_symmetric", "mc_replica"):
                    raise CardError(f"{where}: unknown pdf_method '{ss.pdf_method}'")
            out.setdefault(sample, {})[tree] = ss
    return out


@dataclass
class ChannelSpec:
    name: str
    root_file: str
    bdt_root: str


@dataclass
class Config:
    """combine.C AppConfig: the same JSON keys and defaults."""
    path: str
    channels: list
    output_dir: str
    combine_cmd: str = "combine"
    combine_cards_cmd: str = "combineCards.py"
    eigen_rel_cutoff: float = 1e-10
    use_root_covariance: bool = False
    rescale_shape_modes_to_positive: bool = True
    keep_work: bool = True
    lumi_unc: float = 0.0
    trigger_unc: float = 0.0
    mc_stat_threshold: int = 10
    xsec_unc: list = field(default_factory=list)  # (pattern, fraction) in sorted pattern order
    syst_sums: dict = field(default_factory=dict)  # nuisance -> sample -> channel -> SampleSums
    enabled_nuisances: set = field(default_factory=set)  # empty: all
    scenario_scopes: set = field(default_factory=set)  # empty: all
    data_mode: str = "asimov"
    inputs: dict = field(default_factory=dict)  # resolved input paths, for the manifest

    @property
    def work_dir(self):
        return str(Path(self.output_dir) / "work")

    def enabled(self, name):
        return not self.enabled_nuisances or name in self.enabled_nuisances


def _bool(payload, key, default):
    if key not in payload:
        return default
    if not isinstance(payload[key], bool):
        raise CardError(f"JSON value of '{key}' is not a bool")
    return payload[key]


def load_config(path, output_dir=None, log=log_message):
    """combine.C loadAppConfig. output_dir overrides the config's (relative to the working directory)."""
    abs_path = str(Path(path).resolve())
    base = os.path.dirname(abs_path)
    payload = load_json(abs_path)
    if "channels" not in payload:
        raise CardError("config.json missing 'channels' array")
    channels = []
    for item in payload["channels"]:
        if "bdt_root" not in item:
            raise CardError(f"config.json channel '{item['name']}' missing required 'bdt_root'")
        channels.append(ChannelSpec(item["name"], resolve_path(base, item["root_file"]),
                                    resolve_path(base, item["bdt_root"])))
    if not channels:
        raise CardError("config.json 'channels' is empty")
    out = (str(Path(output_dir).resolve()) if output_dir is not None
           else resolve_path(base, payload.get("output_dir", "./output")))
    cfg = Config(abs_path, channels, out,
                 combine_cmd=payload.get("combine_cmd", "combine"),
                 combine_cards_cmd=payload.get("combine_cards_cmd", "combineCards.py"),
                 eigen_rel_cutoff=float(payload.get("eigen_rel_cutoff", 1e-10)),
                 use_root_covariance=_bool(payload, "use_root_covariance", False),
                 rescale_shape_modes_to_positive=_bool(payload, "rescale_shape_modes_to_positive", True),
                 keep_work=_bool(payload, "keep_work", True),
                 lumi_unc=float(payload.get("lumi_unc", 0.0)),
                 trigger_unc=float(payload.get("trigger_unc", 0.0)),
                 mc_stat_threshold=int(payload.get("mc_stat_threshold", 10)))
    if "enabled_nuisances" in payload:
        known = set(OTHER_NUISANCES) | {s.nuisance for s in RATIO_SPECS}
        for name in payload["enabled_nuisances"]:
            if name not in known:
                raise CardError(f"config.json enabled_nuisances: unknown nuisance '{name}' "
                                f"(known: {', '.join(sorted(known))})")
            cfg.enabled_nuisances.add(name)
    parsed = {}
    for spec in RATIO_SPECS:
        if not cfg.enabled(spec.nuisance):
            continue
        if spec.config_key not in payload:
            raise CardError(f"nuisance '{spec.nuisance}' is enabled but {spec.config_key} is not set in config.json")
        ratio_path = resolve_path(base, payload[spec.config_key])
        if not os.path.exists(ratio_path):
            raise CardError(f"nuisance '{spec.nuisance}' is enabled but {ratio_path} does not exist; "
                            f"run {spec.producer}")
        if ratio_path not in parsed:
            parsed[ratio_path] = load_json(ratio_path)
            log(f"Loaded syst yields: {ratio_path}")
        cfg.syst_sums[spec.nuisance] = load_syst_sums(parsed[ratio_path], spec, ratio_path)
        cfg.inputs[spec.config_key] = ratio_path
    if cfg.enabled("lumi") and not cfg.lumi_unc > 0.0:
        raise CardError("nuisance 'lumi' is enabled but lumi_unc is not positive")
    if cfg.enabled("trigger") and not cfg.trigger_unc > 0.0:
        raise CardError("nuisance 'trigger' is enabled but trigger_unc is not positive")
    if cfg.mc_stat_threshold < 0:
        raise CardError("mc_stat_threshold must be >= 0")
    if cfg.enabled("xsec"):
        if "xsec_unc_json" not in payload:
            raise CardError("nuisance 'xsec' is enabled but xsec_unc_json is not set in config.json")
        xsec_path = resolve_path(base, payload["xsec_unc_json"])
        if not os.path.exists(xsec_path):
            raise CardError(f"nuisance 'xsec' is enabled but {xsec_path} does not exist")
        for pattern, f in load_json(xsec_path)["uncertainties"].items():
            f = float(f)
            if not math.isfinite(f) or f < 0.0 or f >= 1.0:
                raise CardError(f"{xsec_path}: cross-section uncertainty of '{pattern}' must be a fraction in [0, 1)")
            cfg.xsec_unc.append((pattern, f))
        cfg.inputs["xsec_unc_json"] = xsec_path
        log(f"Loaded cross-section uncertainties: {xsec_path}")
    for scope in payload.get("scenario_scopes", []):
        if scope not in ("combined", "class", "sample"):
            raise CardError(f"config.json scenario_scopes: unknown scope '{scope}' (known: combined, class, sample)")
        cfg.scenario_scopes.add(scope)
    cfg.data_mode = payload.get("data_mode", "asimov")
    if cfg.data_mode not in ("asimov", "observed"):
        raise CardError(f"config.json data_mode must be 'asimov' or 'observed', got '{cfg.data_mode}'")
    return cfg


