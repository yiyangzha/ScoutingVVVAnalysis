# -------------------- formatting and parsing as in combine.C --------------------


def slugify(text):
    """combine.C slugify: ASCII alphanumerics lower-cased, everything else '_', outer '_' stripped."""
    out = "".join(c.lower() if c.isascii() and c.isalnum() else "_" for c in text)
    return out.strip("_")


def fixed6(value):
    """std::setprecision(6) << std::fixed."""
    return f"{value:.6f}"


def g10(value):
    """std::setprecision(10) (default float field): the rateParam formula numbers."""
    return f"{value:.10g}"


def _number(token):
    """simple_json: strtold, then the long double rounded to double."""
    return float(np.longdouble(token))


def _no_constant(token):
    raise CardError(f"Invalid JSON number '{token}'")


def _sorted_object(pairs):
    return dict(sorted(pairs, key=lambda kv: kv[0]))


def load_json(path):
    """A JSON file as simple_json sees it: objects in std::map (sorted) key order, numbers via long double."""
    with open(path) as f:
        return json.load(f, object_pairs_hook=_sorted_object, parse_float=_number, parse_int=_number,
                         parse_constant=_no_constant)


def resolve_path(base_dir, target):
    """resolveReferencedPath(FromDir): absolute paths kept, relative ones under base_dir; weakly_canonical."""
    if not target:
        return target
    p = Path(target)
    if not p.is_absolute():
        p = Path(base_dir) / p
    return str(p.resolve())


