@dataclass
class Kappa:
    up: float = 1.0
    down: float = 1.0
    active: bool = False


@dataclass
class FallbackCount:
    cells: int = 0
    fit_range: int = 0
    inclusive: int = 0


def reduce_sums(spec, s, pdf_method):
    """Up / down ratios of merged sums (combine.C reduceSums)."""
    def r(i):
        return s.varied[i] / s.yield_

    k = Kappa(active=True)
    red = spec.reduction
    if red == "updown":
        k.up, k.down = r(0), r(1)
    elif red == "pdf":
        members = [r(i) for i in range(1, 101)]
        center, sigma = r(0), 0.0
        if pdf_method == "mc_replica":
            members.sort()
            center = 0.5 * (members[83] + members[15])
            sigma = 0.5 * (members[83] - members[15])
        else:
            for m in members:
                sigma += (m - center) * (m - center)
            sigma = math.sqrt(sigma)
        sigma_as = 0.5 * abs(r(102) - r(101))
        total = math.sqrt(sigma * sigma + sigma_as * sigma_as)
        k.up, k.down = center + total, center - total
    elif red == "scale":
        k.up, k.down = -math.inf, math.inf
        for i in SCALE_MEMBERS:
            k.up = max(k.up, r(i))
            k.down = min(k.down, r(i))
    elif red == "ps_isr":  # PSWeight [0] isr.murfac = 2.0, [2] isr.murfac = 0.5
        k.up, k.down = r(2), r(0)
    else:  # [1] fsr.murfac = 2.0, [3] fsr.murfac = 0.5
        k.up, k.down = r(3), r(1)
    return k


def _find_region_sums(ss, level, sr_id, mass_bin):
    if level == "inclusive":
        return ss.inclusive
    if level == "window":
        return ss.regions.get(sr_id)
    if level == "fit_range":
        return ss.mass_range.get(sr_id)
    bins = ss.mass_bins.get(sr_id)
    if bins is None or mass_bin < 0 or mass_bin >= len(bins):
        return None
    return bins[mass_bin]


def process_kappa(spec, sums, channel, process, members, sample_info, cell_yield, process_yield, level, sr_id,
                  mass_bin, count):
    """combine.C processKappa: the kappa of the merged member sums, with the n_eff fallback chain
    mass bin -> SR fit range -> inclusive, SR window -> inclusive."""
    if not process_yield > 0.0:
        return Kappa()
    cell = f"channel '{channel}' SR {sr_id}" + (f" mass bin {mass_bin}" if level == "mass_bin" else "")
    found = []
    with_theory = without_theory = 0
    for sample in members:
        if spec.theory:
            if not sample_info[sample].has_theory_weights:
                without_theory += 1
                continue
            with_theory += 1
        ss = sums.get(sample, {}).get(channel)
        if ss is None:
            if cell_yield(sample) > 0.0:
                raise CardError(f"nuisance '{spec.nuisance}' has no sums for sample '{sample}' in {cell}, where the "
                                f"sample has a nonzero yield; re-run {spec.producer}")
            continue
        found.append(ss)
    if with_theory > 0 and without_theory > 0:
        raise CardError(f"nuisance '{spec.nuisance}': process '{process}' mixes samples with and without theory "
                        "weights, whose merged sums are not defined")
    if not found:
        return Kappa()
    for ss in found:
        if ss.min_region_events != found[0].min_region_events or ss.pdf_method != found[0].pdf_method:
            raise CardError(f"nuisance '{spec.nuisance}': the samples of process '{process}' were processed with "
                            "different min_region_events or pdf_method")
    chain = {"mass_bin": ("mass_bin", "fit_range", "inclusive"), "window": ("window", "inclusive")}.get(level, (level,))
    count.cells += 1
    min_events = found[0].min_region_events
    for li, lev in enumerate(chain):
        total = RegionSums()
        for ss in found:
            rs = _find_region_sums(ss, lev, sr_id, mass_bin)
            if rs is None:
                raise CardError(f"nuisance '{spec.nuisance}' has no sums of every sample of '{process}' for {cell}; "
                                f"re-run {spec.producer}" + ("" if lev == "window" else " with the mass_fit config"))
            total.yield_ += rs.yield_
            total.sumw2 += rs.sumw2
            if not total.varied:
                total.varied = [0.0] * len(rs.varied)
                total.varied_sumw2 = [0.0] * len(rs.varied_sumw2)
            for i in range(len(rs.varied)):
                total.varied[i] += rs.varied[i]
                total.varied_sumw2[i] += rs.varied_sumw2[i]

        def enough(s, w2):
            return s > 0.0 and w2 > 0.0 and s * s / w2 >= min_events

        ok = enough(total.yield_, total.sumw2)
        for i in USED_VARIED[spec.reduction]:
            ok = ok and enough(total.varied[i], total.varied_sumw2[i])
        if not ok and li + 1 < len(chain):
            continue
        if not total.yield_ > 0.0:
            raise CardError(f"nuisance '{spec.nuisance}': process '{process}' has a non-positive merged inclusive "
                            f"yield in channel '{channel}'")
        if li > 0 and lev == "fit_range":
            count.fit_range += 1
        if li > 0 and lev == "inclusive":
            count.inclusive += 1
        k = reduce_sums(spec, total, found[0].pdf_method)
        if not k.up > 0.0 or not k.down > 0.0 or not math.isfinite(k.up) or not math.isfinite(k.down):
            raise CardError(f"nuisance '{spec.nuisance}' gives kappa down/up = {k.down:g}/{k.up:g} for process "
                            f"'{process}' in {cell}; a lnN kappa must be positive (the variation removes the whole "
                            "yield)")
        return k
    return Kappa()


def sample_xsec_unc(cfg, sample):
    """Cross-section uncertainty of a sample: the xsec_unc_json pattern(s) matching its name."""
    found, value = False, 0.0
    for pattern, f in cfg.xsec_unc:
        if not fnmatchcase(sample, pattern):
            continue
        if found and f != value:
            raise CardError(f"xsec_unc_json: patterns with different values match sample '{sample}'")
        found, value = True, f
    if not found:
        raise CardError(f"xsec_unc_json has no cross-section uncertainty for sample '{sample}'")
    return value


